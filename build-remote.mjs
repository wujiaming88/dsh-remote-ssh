import {build} from 'esbuild';
import {writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const result=await build({entryPoints:[fileURLToPath(new URL('./lib/durable-worker.js',import.meta.url))],
  bundle:true,write:false,format:'esm',platform:'node',target:'node22',
  external:['@agentclientprotocol/sdk'],treeShaking:true,legalComments:'none',metafile:true});
for(const output of Object.values(result.metafile.outputs))for(const imported of output.imports){
  if(imported.external&&imported.path!=='@agentclientprotocol/sdk'&&!imported.path.startsWith('node:'))throw new Error('Unexpected remote runtime dependency: '+imported.path);
}
const source='// Generated by node build-remote.mjs. Runs on the remote host only.\n'+result.outputFiles[0].text;
await writeFile(new URL('./lib/durable-worker-bundle.js',import.meta.url),source);
console.log(`Built ${Object.keys(result.metafile.inputs).length} remote modules (${Buffer.byteLength(source)} bytes); external SDK remains pinned by remote preparation`);
